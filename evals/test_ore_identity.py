import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

SCRIPT = Path(__file__).resolve().parents[1] / 'skills/ore/scripts/ore_identity.py'
spec = importlib.util.spec_from_file_location('ore_identity', SCRIPT)
identity = importlib.util.module_from_spec(spec)
spec.loader.exec_module(identity)


class IdentityTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.repo = self.root / 'repo'
        self.repo.mkdir()
        self.global_file = self.root / 'config/identity.json'

    def cli(self, *args, success=True):
        result = subprocess.run([sys.executable, str(SCRIPT), *args, '--repo', str(self.repo)],
                                env={**os.environ, 'ORE_IDENTITY_HOME': str(self.global_file.parent)},
                                capture_output=True, text=True, encoding='utf-8')
        self.assertEqual(result.returncode, 0 if success else 2, result.stderr)
        return json.loads(result.stdout) if success else result.stderr

    def test_first_use_and_cross_process_persistence(self):
        self.assertEqual(self.cli('show')['prompt'], identity.FIRST_USE)
        self.cli('change', '--name', 'Aníbal Orellana', '--email', 'private@example.test')
        actual = self.cli('show')
        self.assertEqual(actual['identity']['developers'][0]['name'], 'Aníbal Orellana')
        self.assertNotIn('prompt', actual)
        self.assertFalse((self.repo / '.ore').exists())

    def test_project_collaborators_precedence_and_removal(self):
        self.cli('change', '--name', 'Global', '--email', 'private@example.test')
        self.cli('project', '--name', 'Project', '--additional-developer', '{"name":"Collaborator","team":"Team"}')
        current = self.cli('show')
        self.assertEqual(current['source'], 'project')
        self.assertEqual(len(current['identity']['developers']), 2)
        self.assertNotIn('email', current['identity']['developers'][0])
        self.cli('remove', '--scope', 'project')
        self.assertEqual(self.cli('show')['source'], 'global')
        self.cli('remove')
        self.assertIsNone(self.cli('show')['identity'])

    def test_invalid_input_preserves_profile(self):
        self.cli('change', '--name', 'Original')
        before = self.global_file.read_bytes()
        self.cli('change', '--name', ' ', success=False)
        self.cli('change', '--name', 'Replacement', '--additional-developer', '{"name":"Other","invented":"x"}', success=False)
        self.assertEqual(before, self.global_file.read_bytes())

    def test_corrupt_project_not_silently_ignored(self):
        self.cli('change', '--name', 'Global')
        (self.repo / '.ore').mkdir()
        (self.repo / '.ore/identity.json').write_text('{}', encoding='utf-8')
        self.cli('show', success=False)

    def test_categories_and_read_only(self):
        samples = {'banner.py': '# Generated by Claude\n', 'provider.md': 'Built with OpenAI API provider\n',
                   'LICENSE.txt': 'Generated by Claude\n', 'CHANGELOG.md': 'Generated by Claude\n',
                   'template.ts': 'const example = "Created by Codex";\n', 'credits.txt': 'Co-authored-by: Claude\n'}
        for name, content in samples.items():
            (self.repo / name).write_text(content, encoding='utf-8')
        before = {p.name: p.read_bytes() for p in self.repo.iterdir()}
        result = identity.audit(self.repo, global_file=self.global_file)
        self.assertEqual({f['path']: f['category'] for f in result['findings']},
                         {'banner.py': 'removable-promotion', 'provider.md': 'technical-reference',
                          'LICENSE.txt': 'protected-attribution', 'CHANGELOG.md': 'historical-or-audit',
                          'template.ts': 'human-review', 'credits.txt': 'historical-or-audit'})
        self.assertEqual(before, {p.name: p.read_bytes() for p in self.repo.iterdir()})

    def test_incremental_exclusions_and_escape(self):
        (self.repo / 'new.md').write_text('Made with AI\n')
        (self.repo / 'other.md').write_text('Generated with ChatGPT\n')
        (self.repo / 'node_modules').mkdir()
        (self.repo / 'node_modules/vendor.md').write_text('Made with AI\n')
        result = identity.audit(self.repo, ['new.md'], self.global_file)
        self.assertEqual([f['path'] for f in result['findings']], ['new.md'])
        self.assertEqual(len(identity.audit(self.repo, global_file=self.global_file)['findings']), 2)
        with self.assertRaises(ValueError):
            identity.audit(self.repo, ['../outside.md'], self.global_file)

    def test_coverage_limits(self):
        (self.repo / 'large.md').write_bytes(b'x' * 2_000_001)
        (self.repo / 'broken.txt').write_bytes(b'\xff')
        result = identity.audit(self.repo, global_file=self.global_file)
        self.assertEqual(len(result['skipped']), 2)
        self.assertEqual(result['status'], 'review-required')

    def test_clean_scan_needs_context_and_does_not_leak_profile(self):
        self.cli('change', '--name', 'Private Name', '--email', 'private@example.test')
        result = self.cli('audit')
        self.assertEqual(result['status'], 'context-review-required')
        self.assertNotIn('private@example.test', json.dumps(result))
        self.assertNotIn('Private Name', json.dumps(result))


if __name__ == '__main__':
    unittest.main()
